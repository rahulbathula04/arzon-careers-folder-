function loadImage(url) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => resolve(img);
    img.onerror = (e) => reject(e);
    img.src = url;
  });
}
async function renderCroppedImage(imageUrl, pixels, sourceType) {
  const image = await loadImage(imageUrl);
  const canvas = document.createElement("canvas");
  canvas.width = TARGET_WIDTH;
  canvas.height = TARGET_HEIGHT;
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("Could not create canvas context");
  ctx.imageSmoothingEnabled = true;
  ctx.imageSmoothingQuality = "high";
  ctx.drawImage(
    image,
    pixels.x,
    pixels.y,
    pixels.width,
    pixels.height,
    0,
    0,
    TARGET_WIDTH,
    TARGET_HEIGHT
  );
  const usePng = sourceType === "image/png";
  const contentType = usePng ? "image/png" : "image/jpeg";
  const quality = usePng ? void 0 : 0.9;
  const blob = await new Promise((resolve, reject) => {
    canvas.toBlob(
      (b) => b ? resolve(b) : reject(new Error("Canvas export failed")),
      contentType,
      quality
    );
  });
  return { blob, contentType, ext: usePng ? "png" : "jpg" };
}
